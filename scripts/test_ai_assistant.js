const fetch = require('node-fetch');

const BASE_URL = 'http://localhost:3000/api/assistant';

async function sendChat(payload) {
  const start = Date.now();
  const res = await fetch(`${BASE_URL}/chat`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(payload),
  });
  const duration = Date.now() - start;
  const status = res.status;
  const data = await res.json().catch(() => null);
  return { status, duration, data };
}

async function sendChatStream(payload) {
  const start = Date.now();
  const res = await fetch(`${BASE_URL}/chat/stream`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(payload),
  });
  const status = res.status;
  if (!res.ok || !res.body) {
    const text = await res.text().catch(() => '');
    return { status, duration: Date.now() - start, ttft: null, tokens: [], text, finalResult: null };
  }

  let ttft = null;
  const tokens = [];
  let buffer = '';
  let finalResult = null;
  let accumulated = '';

  const body = res.body;

  return new Promise((resolve) => {
    body.on('data', (chunk) => {
      const now = Date.now();
      buffer += chunk.toString();
      const lines = buffer.split('\n\n');
      buffer = lines.pop() || '';

      for (const line of lines) {
        const trimmed = line.trim();
        if (!trimmed.startsWith('data:')) continue;
        const jsonStr = trimmed.slice(5).trim();
        try {
          const event = JSON.parse(jsonStr);
          if (event.type === 'token' && event.content) {
            if (ttft === null) ttft = now - start;
            tokens.push(event.content);
            accumulated += event.content;
          } else if (event.type === 'done' && event.result) {
            finalResult = event.result;
          }
        } catch (_) {}
      }
    });

    body.on('end', () => {
      const duration = Date.now() - start;
      resolve({
        status,
        duration,
        ttft: ttft !== null ? ttft : duration,
        tokensCount: tokens.length,
        accumulated,
        finalResult,
      });
    });

    body.on('error', (err) => {
      resolve({ status, duration: Date.now() - start, error: err.message });
    });
  });
}

